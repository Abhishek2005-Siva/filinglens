// Packs the AI-server code (backend/app zipped + the Kaggle notebook template) into cf/backend_bundle.ts, because a Cloudflare Worker has no disk to read it from.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { zipSync } from 'fflate'

const root = join(process.cwd(), 'backend')
const list = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n)
  if (n === '__pycache__' || n.endsWith('.pyc')) return []
  return statSync(p).isDirectory() ? list(p) : [p]
})
const files = {}
for (const f of list(join(root, 'app'))) files[relative(root, f).split('\\').join('/')] = new Uint8Array(readFileSync(f))
const zip = Buffer.from(zipSync(files, { level: 6 })).toString('base64')
const template = readFileSync(join(root, 'kaggle', 'server_template.py'), 'utf8')
writeFileSync(join(process.cwd(), 'cf', 'backend_bundle.ts'), `// Generated by scripts/gen-backend.mjs - do not edit.\nexport const appZipB64 = ${JSON.stringify(zip)}\nexport const template = ${JSON.stringify(template)}\n`)
console.log(`cf/backend_bundle.ts: ${Object.keys(files).length} files, ${(zip.length / 1024).toFixed(0)} KB`)
